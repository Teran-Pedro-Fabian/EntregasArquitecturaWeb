CREATE TABLE IF NOT EXISTS notificacion_cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento VARCHAR(64) NOT NULL,
    id_cliente VARCHAR(64) NOT NULL,
    mensaje VARCHAR(500) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_notificacion_evento_cliente UNIQUE (id_evento, id_cliente)
);

CREATE INDEX IF NOT EXISTS ix_notificacion_cliente_fecha
    ON notificacion_cliente (id_cliente, fecha_creacion DESC);
